test('failed step save, completion and removal preserve both stored data and the current step until retry', async ({ page }, testInfo) => {
  const parent = task('step-failure', '2026-09-03T15:00', 240)
  await seed(page, [parent])
  await openMenu(page, parent.title)
  await step(page, parent.title).click()
  await fillStep(page, 'Lag en disposisjon', '20')
  const before = await raw(page)
  await page.evaluate(() => { window.failWrite = true })
  await saveStep(page).click()
  expect(await raw(page)).toBe(before)
  await expect(page.locator('#step-form')).toBeVisible()
  await expect(page.locator('#step-description')).toHaveValue('Lag en disposisjon')
  await expect(page.locator('#step-estimatedMinutes')).toHaveValue('20')
  await expect(saveStep(page)).toBeFocused()
  await expect(page.getByRole('status')).toContainText('ikke lagret')
  await page.evaluate(() => { window.failWrite = false })
  await saveStep(page).click()
  for (const action of ['Neste steg gjort', 'Fjern neste steg']) {
    const beforeAction = await raw(page)
    await page.evaluate(() => { window.failWrite = true })
    await openMenu(page, parent.title)
    await step(page, parent.title, action).click()
    expect(await raw(page)).toBe(beforeAction)
    await expect(row(page, parent.title)).toContainText('Lag en disposisjon')
    await expect(checkbox(page, parent.title)).not.toBeChecked()
    await page.evaluate(() => { window.failWrite = false })
  }
  await openMenu(page, parent.title)
  await step(page, parent.title, 'Neste steg gjort').click()
  expect((await saved(page)).tasks).toEqual([parent])
  expect(await writes(page)).toHaveLength(5)
})

