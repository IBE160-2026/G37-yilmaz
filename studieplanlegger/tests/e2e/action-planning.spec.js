test('work completion and confirmed delivery are separate, reversible states with ready work still due', async ({ page }, testInfo) => {
  const submission = { ...task('submission', '2026-09-03T11:59', 20), requiresSubmission: true }
  const ordinary = task('reading', '2026-09-03T15:00', 15)
  await seed(page, [submission, ordinary])
  await openMenu(page, submission.title)
  await work(page, submission.title).check()
  await expect(row(page, submission.title)).toContainText('Klar til levering')
  await expect(row(page, submission.title).getByText('Forfalt', { exact: true })).toBeVisible()
  expect((await saved(page)).tasks[0].submitted).not.toBe(true)
  await filter(page, '30', { alternatives: false })
  expect(await ids(page)).toEqual([ordinary.id])
  await expect(row(page, ordinary.title)).toContainText(/hovedforslag/i)
  await expect(row(page, ordinary.title)).toContainText(/Passer innen 30 minutter.*nærmeste frist/)
  await navigate(page, 'week')
  await expect(row(page, submission.title)).toBeVisible()
  await openMenu(page, submission.title)
  await delivery(page, submission.title).click()
  expect((await saved(page)).tasks[0]).toMatchObject({ completed: true, submitted: true })
  await expect(row(page, submission.title)).toContainText('Levert')
  await expect(row(page, submission.title).getByText('Forfalt', { exact: true })).toBeHidden()
  await expect(work(page, submission.title)).toBeDisabled()
  await openMenu(page, submission.title)
  await edit(page, submission.title).click()
  await expect(page.locator('#requiresSubmission')).toBeChecked()
  await expect(page.locator('#requiresSubmission')).toBeDisabled()
  await page.locator('#cancel-task').click()
  await page.reload()
  await navigate(page, 'week')
  await expect(row(page, submission.title)).toContainText('Levert')
  await openMenu(page, submission.title)
  await delivery(page, submission.title, true).click()
  await expect(row(page, submission.title)).toContainText('Klar til levering')
  expect((await saved(page)).tasks[0]).toMatchObject({ completed: true, submitted: false })
  await openMenu(page, submission.title)
  await work(page, submission.title).uncheck()
  expect((await saved(page)).tasks[0]).toMatchObject({ completed: false, submitted: false, remainingMinutes: null })
  await openMenu(page, submission.title)
  await edit(page, submission.title).click()
  await page.locator('#remainingMinutes').fill('20')
  await save(page).click()
  await openMenu(page, ordinary.title)
  await checkbox(page, ordinary.title).check()
  await expect(row(page, ordinary.title)).toContainText('Fullført')
  await expect(delivery(page, ordinary.title)).toHaveCount(0)
  await filter(page, '30', { alternatives: false })
  expect(await ids(page)).toEqual([submission.id])
})

