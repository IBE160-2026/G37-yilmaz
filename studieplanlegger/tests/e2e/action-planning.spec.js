const localOrigin = `http://127.0.0.1:${process.env.PLAYWRIGHT_PORT || '5174'}`
import { expectModal } from './helpers.js'
import { navigate } from './helpers.js'
import { openMenu, tabTo } from './helpers.js'
import { test, expect } from '@playwright/test'
import { task, seed, rows, row, checkbox, edit, save, saved, raw, writes, ids, filter, fillDraft, expectFocusFits } from './helpers.js'

const step = (page, title, action = 'Legg til neste steg') => row(page, title).getByRole('button', { name: `${action} «${title}»`, exact: true })
const work = (page, title) => row(page, title).getByRole('checkbox', { name: `Ferdig med arbeidet «${title}»`, exact: true, includeHidden: true })
const delivery = (page, title, undo = false) => row(page, title).getByRole('button', { name: `${undo ? 'Angre levering' : 'Bekreft levert'} «${title}»`, exact: true })
const saveStep = page => page.locator('#step-form').getByRole('button', { name: 'Lagre neste steg', exact: true })
const visibleRows = page => page.locator('#task-list li:visible')

async function fillStep(page, description = 'Les oppgaveteksten og lag en disposisjon', minutes = '20') {
  await page.getByLabel('Beskrivelse av neste steg', { exact: true }).fill(description)
  await page.getByLabel('Estimat for neste steg (minutter)', { exact: true }).fill(minutes)
}

test('new submission task and one validated next step persist through edit, reload and reopen', async ({ page, context }, testInfo) => {
  await seed(page, [])
  await page.locator('#new-task').click()
  await fillDraft(page, { title: 'Skriv rapport i IBE160', course: 'IBE160', deadlineLocal: '2026-09-03T15:00', estimatedMinutes: '240' })
  await page.getByRole('checkbox', { name: 'Krever innlevering', exact: true }).check()
  await save(page).click()
  const title = 'Skriv rapport i IBE160'
  await expect(work(page, title)).not.toBeChecked()
  await openMenu(page, title)
  await step(page, title).click()
  const beforeStep = await raw(page)
  for (const minutes of ['', '0', '-1']) {
    await fillStep(page, 'Les oppgaveteksten', minutes)
    await saveStep(page).click()
    await expect(page.locator('#step-estimatedMinutes')).toHaveAttribute('aria-invalid', 'true')
    await expect(page.locator('#step-estimatedMinutes')).toBeFocused()
    await expect(page.locator('#step-description')).toHaveValue('Les oppgaveteksten')
    expect(await raw(page)).toBe(beforeStep)
    expect(await writes(page)).toHaveLength(1)
  }
  await fillStep(page, ' ', '20')
  await saveStep(page).click()
  await expect(page.locator('#step-description')).toHaveAttribute('aria-invalid', 'true')
  await expect(page.locator('#step-description')).toBeFocused()
  expect(await raw(page)).toBe(beforeStep)
  await fillStep(page)
  await saveStep(page).click()
  await expect(page.locator('#step-form')).toBeHidden()
  await expect(row(page, title)).toContainText('Les oppgaveteksten og lag en disposisjon')
  await expect(row(page, title)).toContainText('20 min · bare neste steg')
  await expect(row(page, title)).toContainText('Gjenstående arbeid: 240 min')
  await openMenu(page, title)
  await edit(page, title).click()
  await expect(page.locator('#requiresSubmission')).toBeChecked()
  await page.locator('#course').fill('IBE160 – rapport')
  await save(page).click()
  const expected = await saved(page)
  expect(expected.tasks[0]).toMatchObject({
    title, course: 'IBE160 – rapport', estimatedMinutes: null, remainingMinutes: 240, completed: false, requiresSubmission: true,
    nextStep: { description: 'Les oppgaveteksten og lag en disposisjon', estimatedMinutes: 20 },
  })
  expect(expected.tasks[0].submitted).not.toBe(true)
  await page.reload()
  await navigate(page, 'week')
  await expect(row(page, title)).toContainText('20 min · bare neste steg')
  expect(await saved(page)).toEqual(expected)
  expect(await writes(page)).toEqual([])
  await page.close()
  const reopened = await context.newPage()
  await reopened.goto('/')
  await navigate(reopened, 'all')
  await expect(row(reopened, title)).toContainText('Les oppgaveteksten og lag en disposisjon')
  expect(await saved(reopened)).toEqual(expected)
})

test('edit, remove and complete a next step leave parent estimate, completion and delivery unchanged', async ({ page }, testInfo) => {
  const parent = { ...task('report', '2026-09-03T15:00', 240), requiresSubmission: true,
    nextStep: { description: 'Les oppgaveteksten', estimatedMinutes: 20 } }
  await seed(page, [parent])
  await openMenu(page, parent.title)
  await step(page, parent.title, 'Rediger neste steg').click()
  await expect(page.locator('#step-description')).toHaveValue('Les oppgaveteksten')
  await fillStep(page, 'Lag en disposisjon', '15')
  await saveStep(page).click()
  expect((await saved(page)).tasks[0].nextStep).toEqual({ description: 'Lag en disposisjon', estimatedMinutes: 15 })
  await expect(step(page, parent.title, 'Rediger neste steg')).toHaveCount(1)
  await expect(step(page, parent.title)).toHaveCount(0)
  await openMenu(page, parent.title)
  await step(page, parent.title, 'Fjern neste steg').click()
  const { nextStep: removedStep, ...withoutStep } = parent
  expect(removedStep.estimatedMinutes).toBe(20)
  expect((await saved(page)).tasks[0]).toEqual(withoutStep)
  await openMenu(page, parent.title)
  await step(page, parent.title).click()
  await fillStep(page, 'Finn to kilder', '10')
  await saveStep(page).click()
  await openMenu(page, parent.title)
  await step(page, parent.title, 'Neste steg gjort').click()
  expect((await saved(page)).tasks[0]).toEqual(withoutStep)
  await expect(work(page, parent.title)).not.toBeChecked()
  await expect(row(page, parent.title)).toContainText('Hele oppgaven: 240 min')
  await openMenu(page, parent.title)
  await step(page, parent.title).click()
  await fillStep(page, 'Skriv innledningen', '25')
  await saveStep(page).click()
  await page.reload()
  await navigate(page, 'week')
  expect((await saved(page)).tasks[0]).toEqual({ ...withoutStep, nextStep: { description: 'Skriv innledningen', estimatedMinutes: 25 } })
  await expect(work(page, parent.title)).not.toBeChecked()
})

