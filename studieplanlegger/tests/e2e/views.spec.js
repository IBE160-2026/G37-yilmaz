test('repeated Oslo minutes compare current wall time before, exactly at and after both occurrences', async ({ page }, testInfo) => {
  const repeated = task('repeated', '2026-10-25T02:30')
  await seed(page, [repeated], { now: '2026-10-25T02:29:59+02:00' })
  const control = checkbox(page, repeated.title)
  await openMenu(page, repeated.title)
  const overdue = row(page, repeated.title).getByText('Forfalt', { exact: true })
  await control.focus()
  await expect(overdue).not.toBeVisible()
  await page.clock.runFor(1000)
  await expect(overdue).not.toBeVisible()
  await page.clock.runFor(1000)
  await expect(overdue).toBeVisible()
  await page.clock.setSystemTime(new Date('2026-10-25T02:15:00+01:00'))
  await page.evaluate(() => window.dispatchEvent(new Event('focus')))
  await expect(overdue).not.toBeVisible()
  await page.clock.setSystemTime(new Date('2026-10-25T02:30:00+01:00'))
  await page.evaluate(() => window.dispatchEvent(new Event('focus')))
  await expect(overdue).not.toBeVisible()
  await page.clock.runFor(1000)
  await expect(overdue).toBeVisible()
  await expect(control).toBeFocused()
  await expect(row(page, repeated.title)).toContainText('25. oktober kl. 02:30')
  expect((await saved(page)).tasks).toEqual([repeated])
  expect(await writes(page)).toEqual([])
})

test('changing browser timezone preserves saved wall-clock labels, edit draft and focus without writes', async ({ browser }, testInfo) => {
  // Explicit undefined prevents Playwright from injecting its fixed Oslo fixture default.
  // One CDP session instead owns both timezones, with Oslo set and checked before the switch.
  const context = await browser.newContext({ baseURL: localOrigin, timezoneId: undefined })
  const page = await context.newPage()
  const cdp = await context.newCDPSession(page)
  try {
    await cdp.send('Emulation.setTimezoneOverride', { timezoneId: 'Europe/Oslo' })
    const repeated = task('wall-clock', '2026-10-25T02:30')
    await seed(page, [repeated], { view: 'all', now: '2026-10-25T03:00:00+01:00' })
    expect(await page.evaluate(() => Intl.DateTimeFormat().resolvedOptions().timeZone)).toBe('Europe/Oslo')
    const before = await raw(page)
    await openMenu(page, repeated.title)
    await edit(page, repeated.title).click()
    await page.locator('#course').fill('Ulagret emne')
    await page.locator('#deadlineTime').focus()
    await cdp.send('Emulation.setTimezoneOverride', { timezoneId: '' })
    await cdp.send('Emulation.setTimezoneOverride', { timezoneId: 'America/New_York' })
    await page.evaluate(() => window.dispatchEvent(new Event('focus')))
    expect(await page.evaluate(() => Intl.DateTimeFormat().resolvedOptions().timeZone)).toBe('America/New_York')
    await page.clock.runFor(2000)
    await expect(page.locator('#deadlineLocal')).toHaveValue('2026-10-25T02:30')
    await expect(page.locator('#deadlineTime')).toBeFocused()
    await expect(page.locator('#course')).toHaveValue('Ulagret emne')
    await expect(row(page, repeated.title)).toContainText('25. oktober kl. 02:30')
    expect(await raw(page)).toBe(before)
    expect(await writes(page)).toEqual([])
  } finally { await context.close() }
})
