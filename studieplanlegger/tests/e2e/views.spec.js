test('focus, visibility and view actions refresh a jumped clock without a timer or storage write', async ({ page }, testInfo) => {
  const due = task('focus', '2026-09-03T12:00')
  await seed(page, [due], { now: '2026-09-03T11:59:59+02:00' })
  const before = await raw(page)
  await page.clock.setSystemTime(new Date('2026-09-03T12:00:01+02:00'))
  await page.evaluate(() => window.dispatchEvent(new Event('focus')))
  await expect(row(page, due.title).getByText('Forfalt', { exact: true })).toBeVisible()
  await page.clock.setSystemTime(new Date('2026-09-03T11:59:59+02:00'))
  await page.evaluate(() => document.dispatchEvent(new Event('visibilitychange')))
  await expect(row(page, due.title).getByText('Forfalt', { exact: true })).not.toBeVisible()
  await page.clock.setSystemTime(new Date('2026-09-03T12:00:01+02:00'))
  await navigate(page, 'all')
  await expect(row(page, due.title).getByText('Forfalt', { exact: true })).toBeVisible()
  await page.clock.setSystemTime(new Date('2026-09-03T11:59:59+02:00'))
  await openMenu(page, due.title)
  await edit(page, due.title).click()
  await page.locator('#course').fill('Ulagret mens siden er skjult')
  await expect(page.locator('#course')).toBeFocused()
  await expect(row(page, due.title).getByText('Forfalt', { exact: true })).not.toBeVisible()
  // Simulate Page Visibility API state; this does not minimize a physical browser window.
  await page.evaluate(() => {
    window.simulatedHidden = true
    Object.defineProperty(document, 'hidden', { configurable: true, get: () => window.simulatedHidden })
    Object.defineProperty(document, 'visibilityState', { configurable: true, get: () => window.simulatedHidden ? 'hidden' : 'visible' })
    document.dispatchEvent(new Event('visibilitychange'))
  })
  await page.clock.runFor(2000)
  await expect(row(page, due.title).getByText('Forfalt', { exact: true })).not.toBeVisible()
  await expect(page.locator('#course')).toHaveValue('Ulagret mens siden er skjult')
  await expect(page.locator('#course')).toBeFocused()
  expect(await writes(page)).toEqual([])
  await page.evaluate(() => {
    window.simulatedHidden = false
    document.dispatchEvent(new Event('visibilitychange'))
  })
  await expect(row(page, due.title).getByText('Forfalt', { exact: true })).toBeVisible()
  await expect(page.locator('#course')).toHaveValue('Ulagret mens siden er skjult')
  await expect(page.locator('#course')).toBeFocused()
  expect(await raw(page)).toBe(before)
  expect(await writes(page)).toEqual([])
})

