import { test, expect } from '@playwright/test'
import { task, seed, saved, raw, writes, fillDraft, fillDeadline, openMenu, edit, save, navigate, row } from './helpers.js'

const repeated = '2027-10-31T02:30'
const calendarDay = async (page, date) => {
  await navigate(page, 'calendar')
  await page.locator('#full-calendar-date').fill(date)
  await page.locator('#full-calendar-date').press('Tab')
  await page.locator('#full-calendar').getByRole('button', { name: 'Dag', exact: true }).click()
}

for (const [choice, offset, label, width] of [['earlier', '+02:00', 'første', 1280], ['later', '+01:00', 'andre', 360]]) {
  test(`autumn deadline requires ${choice} choice and preserves it in edit and calendar at ${width}px`, async ({ page }, testInfo) => {
    await page.setViewportSize({ width, height: 900 })
    await seed(page, [task('existing')], { view: 'all', now: '2027-10-30T12:00:00+02:00' })
    const before = await raw(page)
    await page.locator('#new-task').click()
    await fillDraft(page, { title: 'Frist ved vintertid', remainingMinutes: 45, deadlineLocal: repeated })
    const select = page.getByLabel('Hvilket klokkeslett mener du?')
    await expect(select).toBeVisible()
    await expect(select).toHaveValue('')
    await expect(page.locator('#deadline-occurrence-help')).toContainText('finnes to ganger')
    await save(page).click()
    await expect(page.locator('#deadlineDisambiguation-error')).toContainText('Velg første eller andre')
    await expect(select).toBeFocused()
    expect(await raw(page)).toBe(before)
    expect(await writes(page)).toHaveLength(0)
    await select.selectOption(choice)
    await expect(page.locator('#deadline-choice-info')).toContainText(`UTC${offset}`)
    await page.clock.runFor(1500)
    await expect(select).toHaveValue(choice)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: testInfo.outputPath(`deadline-${choice}-${width}.png`), fullPage: true })
    await save(page).click()
    await expect(page.locator('#task-form')).toBeHidden()
    const created = (await saved(page)).tasks.find(item => item.title === 'Frist ved vintertid')
    expect(created).toMatchObject({ deadlineLocal: repeated, deadlineDisambiguation: choice })
    await expect(row(page, created.title)).toContainText(`${label} gang, UTC${offset}`)
    await page.reload()
    await navigate(page, 'all')
    await openMenu(page, created.title)
    await edit(page, created.title).click()
    await expect(select).toHaveValue(choice)
    await page.locator('#cancel-task').click()
    await expect(edit(page, created.title)).toBeFocused()
    await calendarDay(page, '2027-10-31')
    const entry = page.locator(`#full-calendar [data-calendar-key="task:${created.id}"]`).first()
    await expect(entry).toContainText(`UTC${offset}`)
    await expect(entry).not.toContainText('må presiseres')
    await entry.click()
    await expect(page.locator('dialog[open]')).toContainText(`UTC${offset}`)
    await page.locator('dialog[open]').getByRole('button', { name: 'Rediger', exact: true }).click()
    await expect(select).toHaveValue(choice)
  })
}

test('clock format and nonexistent spring minute give distinct errors, focus time and retain the draft', async ({ page }) => {
  await seed(page, [task('existing')], { view: 'all' })
  const before = await raw(page)
  await page.locator('#new-task').click()
  await fillDraft(page, { title: 'Behold dette utkastet', remainingMinutes: 45, deadlineLocal: '2027-03-28T25:90' })
  await save(page).click()
  await expect(page.locator('#deadlineLocal-error')).toContainText('00:00 til 23:59')
  await expect(page.locator('#deadlineLocal-error')).not.toContainText('gyldig dato')
  await expect(page.locator('#deadlineTime')).toBeFocused()
  await expect(page.locator('#deadlineTime')).toHaveAttribute('aria-invalid', 'true')
  await expect(page.locator('#deadlineDate')).toHaveAttribute('aria-invalid', 'false')
  await page.locator('#deadlineTime').fill('02:30')
  await save(page).click()
  await expect(page.locator('#deadlineLocal-error')).toContainText('02:30 finnes ikke 28.3.2027')
  await expect(page.locator('#deadlineLocal-error')).toContainText('sommertid')
  await expect(page.locator('#deadlineTime')).toBeFocused()
  await expect(page.locator('#title')).toHaveValue('Behold dette utkastet')
  await expect(page.locator('#remainingMinutes')).toHaveValue('45')
  await expect(page.locator('#deadlineDate')).toHaveValue('2027-03-28')
  expect(await raw(page)).toBe(before)
  expect(await writes(page)).toHaveLength(0)
  await page.locator('#deadlineTime').fill('03:30')
  await save(page).click()
  await expect(page.locator('#task-form')).toBeHidden()
  const created = (await saved(page)).tasks.find(item => item.title === 'Behold dette utkastet')
  expect(created).toMatchObject({ deadlineLocal: '2027-03-28T03:30' })
  await page.reload()
  await navigate(page, 'all')
  await expect(row(page, created.title)).toContainText('28. mars 2027 kl. 03:30')
})

test('legacy ambiguity can be repaired; failed saves retain the choice and changing the deadline clears it', async ({ page }) => {
  const old = { ...task('legacy', repeated), title: 'Eldre tvetydig frist' }
  await seed(page, [old], { view: 'all', now: '2027-10-30T12:00:00+02:00' })
  const before = await raw(page)
  await expect(row(page, old.title)).toContainText('velg første eller andre gang')
  await openMenu(page, old.title)
  await edit(page, old.title).click()
  const select = page.locator('#deadlineDisambiguation')
  await expect(select).toHaveValue('')
  await select.selectOption('later')
  await page.evaluate(() => { window.failWrite = true })
  await save(page).click()
  await expect(page.locator('#feedback')).toContainText('ikke lagret')
  await expect(select).toHaveValue('later')
  expect(await raw(page)).toBe(before)
  await page.evaluate(() => { window.failWrite = false })
  await save(page).click()
  await expect(page.locator('#task-form')).toBeHidden()
  expect((await saved(page)).tasks[0]).toMatchObject({ id: old.id, deadlineDisambiguation: 'later' })
  await openMenu(page, old.title)
  await edit(page, old.title).click()
  await fillDeadline(page, '2027-11-01T02:30')
  await expect(page.locator('#deadlineOccurrence')).toBeHidden()
  await expect(select).toHaveValue('')
  await fillDeadline(page, repeated)
  await expect(select).toHaveValue('')
  await save(page).click()
  await expect(select).toBeFocused()
  await fillDeadline(page, '2027-11-01T02:30')
  await save(page).click()
  await expect(page.locator('#task-form')).toBeHidden()
  expect((await saved(page)).tasks[0]).not.toHaveProperty('deadlineDisambiguation')
})

test('date-only deadlines remain date-only through creation, calendar, editing and reload', async ({ page }) => {
  await seed(page, [task('existing')], { view: 'all', now: '2027-10-30T12:00:00+02:00' })
  await page.locator('#new-task').click()
  await fillDraft(page, { title: 'Frist uten klokkeslett', remainingMinutes: 30, deadlineLocal: '2027-10-31' })
  await expect(page.locator('#deadlineOccurrence')).toBeHidden()
  await save(page).click()
  const created = (await saved(page)).tasks.find(item => item.title === 'Frist uten klokkeslett')
  expect(created.deadlineLocal).toBe('2027-10-31')
  expect(created).not.toHaveProperty('deadlineDisambiguation')
  await calendarDay(page, '2027-10-31')
  const entry = page.locator(`#full-calendar [data-calendar-key="task:${created.id}"]`).first()
  await expect(entry).toContainText('klokkeslett ikke oppgitt')
  await expect(entry).not.toContainText('00:00')
  await navigate(page, 'all')
  await openMenu(page, created.title)
  await edit(page, created.title).click()
  await expect(page.locator('#deadlineTime')).toHaveValue('')
  await fillDeadline(page, repeated)
  await page.locator('#deadlineDisambiguation').selectOption('later')
  await save(page).click()
  await openMenu(page, created.title)
  await edit(page, created.title).click()
  await page.locator('#deadlineTime').fill('')
  await expect(page.locator('#deadlineOccurrence')).toBeHidden()
  await expect(page.locator('#deadlineDisambiguation')).toHaveValue('')
  await save(page).click()
  await page.reload()
  await navigate(page, 'all')
  const persisted = (await saved(page)).tasks.find(item => item.id === created.id)
  expect(persisted.deadlineLocal).toBe('2027-10-31')
  expect(persisted).not.toHaveProperty('deadlineDisambiguation')
  await openMenu(page, created.title)
  await edit(page, created.title).click()
  await expect(page.locator('#deadlineDate')).toHaveValue('2027-10-31')
  await expect(page.locator('#deadlineTime')).toHaveValue('')
  await expect(page.locator('#deadlineOccurrence')).toBeHidden()
})
