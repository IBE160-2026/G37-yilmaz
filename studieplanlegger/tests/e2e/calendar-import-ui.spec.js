  await expect(groups).toHaveCount(2)
  await expect(groups.nth(0).locator('summary').first()).toContainText('SYN777 · Syntetisk A · Høst · 2026 · 7 oppføringer')
  await expect(groups.nth(1).locator('summary').first()).toContainText('SYN777 · Syntetisk B · Vår · 2027 · 7 oppføringer')
  await preview.locator('.document-institutions > summary').click()
  const firstAffiliation = preview.getByRole('combobox', { name: /Lærested for SYN777 ·.*Syntetisk A/ })
  const secondAffiliation = preview.getByRole('combobox', { name: /Lærested for SYN777 ·.*Syntetisk B/ })
  await expect(firstAffiliation).toHaveCount(1); await expect(secondAffiliation).toHaveCount(1)
  await expect(firstAffiliation).toHaveValue('Syntetisk A'); await expect(secondAffiliation).toHaveValue('Syntetisk B')
  await expect(firstAffiliation.locator('option:checked')).toHaveText('Syntetisk A')
  await expect(secondAffiliation.locator('option:checked')).toHaveText('Syntetisk B')
  const course = preview.locator('.document-preview-row').filter({ has: page.locator('[data-field=courseTarget]') }).first()
