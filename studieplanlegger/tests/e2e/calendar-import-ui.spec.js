  await page.getByLabel('Velg fil', { exact: true }).setInputFiles({ name: 'synthetic-contexts.ics', mimeType: 'text/calendar', buffer: Buffer.from(contextCalendar) })
  await page.getByRole('button', { name: 'Vis forhåndsvisning', exact: true }).click()
