import { reveal } from './helpers.js'
import { test, expect } from '@playwright/test'
import { navigate, key, instrumentWrites, writes, openImportMethod } from './helpers.js'

// Invented data only: two course proposals, a point and an all-day entry.
const event = (id, fields) => `BEGIN:VEVENT\r\nUID:synthetic-ui-${id}\r\nSUMMARY:Synthetic ${id}\r\n${fields}\r\nEND:VEVENT`
const calendar = `BEGIN:VCALENDAR\r\nVERSION:2.0\r\n${[
  ...Array.from({ length: 24 }, (_, i) => event(i, `DTSTART:20261026T090000Z\r\nDTEND:20261026T100000Z\r\nX-COURSE-CODE:SYN901\r\nX-COURSE-NAME:Syntetisk navngitt emne`)),
  event('code', 'DTSTART:20261027T090000Z\r\nDTEND:20261027T100000Z\r\nX-COURSE-CODE:SYN902'),
  event('point', 'DTSTART:20261028T090000Z'),
  event('day', 'DTSTART;VALUE=DATE:20261029\r\nDTEND;VALUE=DATE:20261030'),
].join('\r\n')}\r\nEND:VCALENDAR`
const saved = page => page.evaluate(key => JSON.parse(localStorage.getItem(key)), key)

for (const entry of ['calendar', 'file', 'method', 'assignment']) test(`empty planner completes mixed calendar from ${entry}`, async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/'); await instrumentWrites(page); await page.reload()
  await page.addStyleTag({ content: 'html { font-size: 150% !important; }' })
  if (entry === 'assignment') { await navigate(page, 'overview'); await (await reveal(page.getByRole('button', { name: 'Legg inn arbeidskrav', exact: true }))).click() }
  else {
    await navigate(page, 'subjects')
    if (entry === 'method') await openImportMethod(page, 'document')
    else await (await reveal(page.getByRole('button', { name: 'Importer', exact: true }))).click()
  }
  await expect(page.getByLabel('Kalenderperiode', { exact: true })).toHaveValue('automatic')
  await page.getByLabel('Velg fil', { exact: true }).setInputFiles({ name: 'synthetic-ui.ics', mimeType: 'text/calendar', buffer: Buffer.from(calendar) })
  await (await reveal(page.getByRole('button', { name: 'Vis forhåndsvisning', exact: true }))).click()
  const preview = page.locator('.document-preview'), confirm = preview.getByRole('button', { name: 'Importer valgte' })
  await expect(preview).toContainText('1 må avklares')
  await expect(preview.locator('.document-preview-group[open]')).toHaveCount(0)
  await (await reveal(confirm)).click()
  await expect(preview.locator('[data-field=title][aria-invalid=true]')).toBeFocused()
  expect(await writes(page)).toHaveLength(0)
  await (await reveal(page.getByRole('button', { name: 'Bruk emnekoden som foreløpig navn' }))).click()
  await expect(preview.locator('[data-field=title][aria-invalid=true]')).toHaveCount(0)
  await expect(preview.getByRole('alert')).toBeEmpty()
  await expect(preview).toContainText('0 må avklares')
  await expect(preview.locator('.document-preview-row > summary').filter({ hasText: 'Mangler navn' })).toHaveCount(0)
  const group = preview.locator('.document-preview-group').filter({ has: page.locator('summary').filter({ hasText: 'SYN901' }) })
  await (await reveal(group.locator('summary').first())).click()
  const first = group.locator('.document-preview-row').first(); await (await reveal(first.locator('summary').first())).click()
  await (await reveal(first.getByLabel('Ta med i planen', { exact: true }))).uncheck()
  await (await reveal(confirm)).focus(); await confirm.press('Enter')
  await expect(page.getByText('Planen er lagret:', { exact: false })).toBeVisible()
  expect(await writes(page)).toHaveLength(1)
  const result = await saved(page)
  expect(result.planner.courses).toHaveLength(2)
  expect(result.planner.courses.find(course => course.code === 'SYN902').name).toBe('SYN902')
  expect(result.planner.events).toHaveLength(26)
  expect(result.planner.events.filter(event => !event.courseId)).toHaveLength(2)
  expect(result.planner.events.find(event => event.point)).toMatchObject({ start: '2026-10-28T09:00:00.000Z', end: '2026-10-28T09:00:00.000Z' })
  expect(result.planner.events.find(event => event.allDay).end).toBe('2026-10-29T23:00:00.000Z')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.reload(); expect((await saved(page)).planner).toEqual(result.planner)
})

test('snapshot link uses safe endpoint, preserves warnings and creates a course in the shared draft', async ({ page }) => {
  await page.goto('/'); await instrumentWrites(page); await page.reload(); await navigate(page, 'subjects')
  const content = `BEGIN:VCALENDAR\r\nVERSION:2.0\r\n${event('link', 'DTSTART:20261026T090000Z')}\r\nEND:VCALENDAR`
  await page.route('**/api/import/calendar', route => route.fulfill({ json: { calendar: content, calendarUrl: 'https://tp.example.test/synthetic.ics', warnings: ['Syntetisk kildevarsel'] } }))
  await openImportMethod(page, 'calendar')
  await expect(page.getByLabel('Emne for kalenderen')).toBeHidden()
  await (await reveal(page.getByLabel('Kalenderlenke (HTTPS eller webcal)'))).fill('https://tp.example.test/synthetic')
  await (await reveal(page.getByRole('button', { name: 'Vis forhåndsvisning' }))).click()
  const preview = page.locator('.document-preview')
  await expect(preview).toContainText('Syntetisk kildevarsel')
  await expect(preview).toContainText('Den oppdateres ikke automatisk')
  await (await reveal(preview.getByRole('button', { name: 'Opprett nytt emne for gruppen uten emne' }))).click()
  await (await reveal(preview.getByLabel('Emnenavn', { exact: true }))).fill('Syntetisk selvvalgt emne')
  await (await reveal(preview.getByLabel('Kalendersemester', { exact: true }))).selectOption('autumn')
  await (await reveal(preview.getByLabel('År', { exact: true }))).fill('2026')
  expect(await writes(page)).toHaveLength(0)
  await (await reveal(preview.getByRole('button', { name: 'Importer valgte' }))).click()
  await expect(page.getByText('Planen er lagret:', { exact: false })).toBeVisible()
  const result = await saved(page)
  expect(result.planner.sources).toHaveLength(0)
  expect(result.planner.events[0].courseId).toBe(result.planner.courses[0].id)
  expect(result.importSources[0].warnings).toContain('Syntetisk kildevarsel')
  expect(result.importSources[0].name).toBe('Kalenderlenke – øyeblikksbilde')
})

