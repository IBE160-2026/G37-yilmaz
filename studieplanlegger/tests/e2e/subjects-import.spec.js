import { reveal } from './helpers.js'
import { test, expect } from '@playwright/test'
import { openCourseImport, openImportMethod, openTaskDetails } from './helpers.js'

const course = { id: 'isolated-course', name: 'Isolert emne', code: 'TEST101', university: 'Testuniversitet', semester: 'autumn', year: 2026, credits: null, notes: '' }
const ics = `BEGIN:VCALENDAR\r\nVERSION:2.0\r\nPRODID:-//Isolated E2E//EN\r\nBEGIN:VEVENT\r\nUID:isolated-event\r\nDTSTART;TZID=Europe/Oslo:20261019T100000\r\nDTEND;TZID=Europe/Oslo:20261019T110000\r\nRRULE:FREQ=WEEKLY;COUNT=2\r\nSUMMARY:Isolert forelesning\r\nLOCATION:Testrom\r\nEND:VEVENT\r\nEND:VCALENDAR\r\n`
async function seed(page, tasks = [], planner = { courses: [course], events: [], sources: [] }) {
  await page.clock.setFixedTime(new Date('2026-09-07T08:00:00Z'))
  await page.addInitScript(data => { if (!localStorage.getItem('studieplanlegger:v1')) localStorage.setItem('studieplanlegger:v1', JSON.stringify(data)) }, { schemaVersion: 1, tasks, planner })
  await page.goto('/')
}
const task = (id, patch = {}) => ({ id, title: `Isolert ${id}`, course: 'TEST101', deadlineLocal: '2026-09-08T12:00', estimatedMinutes: 30, completed: false, ...patch })

test('visible suggestions, synchronized minutes, correct task opening and delivery reminder', async ({ page }) => {
  const errors = []; page.on('pageerror', e => errors.push(e.message))
  await seed(page, [task('best', { remainingMinutes: 20, splittable: false, nextStep: { description: 'Teststeg', estimatedMinutes: 20 } }), task('other', { estimatedMinutes: 45, splittable: false }), task('unknown', { estimatedMinutes: null }), task('ready', { requiresSubmission: true, completed: true }), task('done', { completed: true })])
  const suggestions = page.locator('#dashboard-suggestions')
  await expect(suggestions.locator('[data-task-id="best"]')).toBeVisible()
  await expect(suggestions).toContainText('Passer innen 30 minutter')
  await expect(suggestions).toContainText('Hele oppgaven er ikke ferdig etter steget')
  await expect(page.locator('#filter-summary')).toHaveText('1 forslag innen 30 minutter.')
  await (await reveal(suggestions.locator('[data-task-id="best"] .task-menu > summary'))).click()
  await (await reveal(suggestions.getByRole('button', { name: 'Rediger «Isolert best»', exact: true }))).click()
  await expect(page.locator('#title')).toHaveValue('Isolert best')
  await (await reveal(page.locator('#cancel-task'))).click()
  await (await reveal(suggestions.locator('[data-task-id="best"] .task-menu > summary'))).click()
  await (await reveal(page.locator('#available-minutes'))).fill('45')
  await expect(page.locator('[data-minutes="45"]')).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('#filter-summary')).toHaveText('2 forslag innen 45 minutter.')
  await (await reveal(page.locator('#toggle-alternatives'))).click()
  await expect(suggestions.locator('[data-task-id="other"]')).toBeVisible()
  await (await reveal(page.locator('[data-minutes="15"]'))).click()
  await expect(page.locator('#available-minutes')).toHaveValue('15')
  await expect(page.locator('#suggestion-empty')).toBeVisible()
  await (await reveal(page.locator('#available-minutes'))).fill('0')
  await expect(page.locator('#available-minutes-error')).not.toBeEmpty()
  await expect(page.locator('#delivery-reminders')).toContainText('Isolert ready')
  expect(errors).toEqual([])
})

