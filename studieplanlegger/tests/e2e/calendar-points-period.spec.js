import { reveal } from './helpers.js'
import { test, expect } from '@playwright/test'
import { navigate, key, instrumentWrites, writes } from './helpers.js'

// Entirely invented source data.
const calendar = `BEGIN:VCALENDAR\r\nVERSION:2.0\r\nBEGIN:VEVENT\r\nUID:synthetic-point\r\nSUMMARY:Syntetisk markering\r\nDTSTART:20261026T090000Z\r\nEND:VEVENT\r\nBEGIN:VEVENT\r\nUID:synthetic-interval\r\nSUMMARY:Syntetisk undervisning\r\nDTSTART:20261026T100000Z\r\nDTEND:20261026T110000Z\r\nEND:VEVENT\r\nEND:VCALENDAR`
const file = { name: 'synthetic-points.ics', mimeType: 'text/calendar', buffer: Buffer.from(calendar) }
const saved = page => page.evaluate(key => JSON.parse(localStorage.getItem(key)), key)

for (const mobile of [false, true]) test(`calendar points and visible period correction ${mobile ? 'mobile' : 'desktop'}`, async ({ page }, info) => {
  if (mobile) await page.setViewportSize({ width: 390, height: 844 })
  await page.clock.setFixedTime(new Date('2026-10-26T08:00:00Z'))
  await page.goto('/'); await instrumentWrites(page); await page.reload()
  await navigate(page, 'subjects')
  await (await reveal(page.getByRole('button', { name: 'Importer', exact: true }))).click()
  await page.getByLabel('Velg fil', { exact: true }).setInputFiles(file)
  await page.getByRole('button', { name: 'Vis forhåndsvisning', exact: true }).click()
  const preview = page.locator('.document-preview')
  await expect(preview).toContainText('Aktiv periode: Automatisk fra filen.')
  await expect(preview).toContainText('2 beholdt')
  await expect(preview).toContainText('0 må avklares')
  await expect(preview).not.toContainText('Kilden er ikke bekreftet fullstendig')
  expect(await writes(page)).toHaveLength(0)
  await (await reveal(preview.getByRole('button', { name: 'Endre periode', exact: true, includeHidden: true }))).click()
  await expect(page.getByLabel('Kalenderperiode', { exact: true })).toBeFocused()
  await (await reveal(page.getByLabel('Kalenderperiode', { exact: true }))).selectOption('manual')
  await (await reveal(page.getByLabel('Kalendersemester for ICS-undervisning'))).selectOption('spring')
  await (await reveal(page.getByLabel('År for ICS-undervisning'))).fill('2025')
  await (await reveal(page.getByRole('button', { name: 'Vis forhåndsvisning', exact: true }))).click()
  await expect(preview).toContainText('Aktivt periodefilter:')
  await expect(preview).toContainText('2 utenfor periode eller uten forekomster')
  await expect(preview.getByRole('status').first()).toHaveText('0 legges til · 0 oppdateres · 0 beholdes · 0 må avklares.')
  await (await reveal(preview.getByText('Antall, utvalg og endringer', { exact: true }))).click()
  await expect(preview.getByText('0 valgte emner · 0 valgte kalenderhendelser (0 punktmarkører) · 0 valgte oppgaver · 0 utelatte oppføringer.', { exact: true })).toBeVisible()
  await expect(preview).toContainText('Endre periode for å vise filens datoer')
  await page.screenshot({ path: info.outputPath('empty-filter.png'), fullPage: true })
  await (await reveal(preview.getByRole('button', { name: 'Endre periode', exact: true, includeHidden: true }))).click()
  await (await reveal(page.getByLabel('Kalenderperiode', { exact: true }))).selectOption('automatic')
  await (await reveal(page.getByRole('button', { name: 'Vis forhåndsvisning', exact: true }))).click()
  await expect(preview).toContainText('2 beholdt')
  await page.screenshot({ path: info.outputPath('points-preview.png'), fullPage: true })
  const confirm = preview.getByRole('button', { name: 'Importer valgte', exact: true })
  await (await reveal(confirm)).focus(); await confirm.press('Enter')
  await expect(page.getByText('Planen er lagret:', { exact: false })).toBeVisible()
  expect(await writes(page)).toHaveLength(1)
  const first = await saved(page)
  expect(first.tasks).toHaveLength(0)
  expect(first.planner.events).toHaveLength(2)
  const point = first.planner.events.find(e => e.point)
  expect(point.start).toBe(point.end)
  await page.reload(); expect((await saved(page)).planner).toEqual(first.planner)
  await navigate(page, 'subjects')
  await (await reveal(page.getByRole('button', { name: 'Rediger undervisning Syntetisk markering', exact: true }))).click()
  await (await reveal(page.locator('#subject-editor [name=startLocal]'))).fill('2026-10-26T12:00')
  await expect(page.locator('#subject-editor [name=endLocal]')).toHaveValue('')
  await (await reveal(page.getByRole('button', { name: 'Lagre undervisning', exact: true }))).click()
  const moved = (await saved(page)).planner.events.find(e => e.id === point.id)
  expect(moved.point).toBe(true); expect(moved.start).toBe(moved.end)
  await navigate(page, 'calendar')
  await expect(page.locator('#calendar-host')).toContainText('Syntetisk markering')
  await page.screenshot({ path: info.outputPath('points-calendar.png'), fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

