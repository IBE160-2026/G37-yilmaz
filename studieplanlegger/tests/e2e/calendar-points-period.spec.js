test('period changes retain corrections and choices; a rejected mixed write leaves full storage unchanged for retry', async ({ page }) => {
  await page.goto('/')
  await page.evaluate(key => localStorage.setItem(key, JSON.stringify({ schemaVersion: 1, tasks: [], planner: { courses: [], events: [], sources: [] } })), key)
  await instrumentWrites(page); await page.reload()
  await navigate(page, 'subjects')
  await (await reveal(page.getByRole('button', { name: 'Importer', exact: true }))).click()
  await page.getByLabel('Velg fil', { exact: true }).setInputFiles(file)
  await page.getByRole('button', { name: 'Vis forhåndsvisning', exact: true }).click()
  const preview = page.locator('.document-preview')
  const point = preview.locator('.document-preview-row').first()
  const interval = preview.locator('.document-preview-row').nth(1)
  await (await reveal(point.locator('summary').first())).click()
  await (await reveal(point.getByLabel('Navn', { exact: true }))).fill('Rettet syntetisk markering')
  await (await reveal(point.getByLabel('Sted (valgfritt)', { exact: true }))).fill('Syntetisk rom')
  await (await reveal(interval.locator('summary').first())).click()
  await (await reveal(interval.getByLabel('Ta med i planen', { exact: true }))).uncheck()
  await (await reveal(preview.getByRole('button', { name: 'Endre periode', exact: true, includeHidden: true }))).click()
  await (await reveal(page.getByLabel('Kalenderperiode', { exact: true }))).selectOption('manual')
  await (await reveal(page.getByLabel('Kalendersemester for ICS-undervisning'))).selectOption('spring')
  await (await reveal(page.getByLabel('År for ICS-undervisning'))).fill('2025')
  await (await reveal(page.getByRole('button', { name: 'Vis forhåndsvisning', exact: true }))).click()
  await expect(preview).toContainText('2 utenfor periode eller uten forekomster')
  await (await reveal(preview.getByRole('button', { name: 'Endre periode', exact: true, includeHidden: true }))).click()
  await (await reveal(page.getByLabel('Kalenderperiode', { exact: true }))).selectOption('automatic')
  await (await reveal(page.getByRole('button', { name: 'Vis forhåndsvisning', exact: true }))).click()
  await expect(preview).toContainText('Utvidelsesvindu:')
  await (await reveal(point.locator('summary').first())).click()
  await expect(point.getByLabel('Navn', { exact: true })).toHaveValue('Rettet syntetisk markering')
  await expect(point.getByLabel('Sted (valgfritt)', { exact: true })).toHaveValue('Syntetisk rom')
  await (await reveal(interval.locator('summary').first())).click()
  await expect(interval.getByLabel('Ta med i planen', { exact: true })).not.toBeChecked()
  await (await reveal(interval.getByLabel('Ta med i planen', { exact: true }))).check()
  const before = await page.evaluate(() => Object.fromEntries(Object.keys(localStorage).map(key => [key, localStorage.getItem(key)])))
  await page.evaluate(() => { window.failWrite = true })
  await (await reveal(preview.getByRole('button', { name: 'Importer valgte', exact: true }))).click()
  await expect(preview.getByRole('alert')).not.toBeEmpty()
  expect(await page.evaluate(() => Object.fromEntries(Object.keys(localStorage).map(key => [key, localStorage.getItem(key)])))).toEqual(before)
  await expect(point.getByLabel('Navn', { exact: true })).toHaveValue('Rettet syntetisk markering')
  await expect(interval.getByLabel('Ta med i planen', { exact: true })).toBeChecked()
  await page.evaluate(() => { window.failWrite = false })
  await (await reveal(preview.getByRole('button', { name: 'Importer valgte', exact: true }))).click()
  await expect(page.getByText('Planen er lagret:', { exact: false })).toBeVisible()
  const result = await saved(page)
  expect(result.planner.events).toHaveLength(2)
  expect(result.planner.events.find(event => event.point)).toMatchObject({ title: 'Rettet syntetisk markering', location: 'Syntetisk rom' })
})
