// Independently invented input; no personal export or calendar is used.
const ics = title => ['BEGIN:VCALENDAR', 'VERSION:2.0', ...Array.from({ length: 108 }, (_, i) => {
  const date = new Date(Date.UTC(2041, 2, i + 1)).toISOString().slice(0, 10).replaceAll('-', '')
  return ['BEGIN:VEVENT', `UID:invented-continuation-${i}@example.invalid`, `SUMMARY:${title} ${i % 2 + 1}`, `X-COURSE-CODE:SYN${810 + i % 4}`, `DTSTART:${date}T090000Z`, `DTEND:${date}T100000Z`, 'END:VEVENT'].join('\r\n')
}), 'END:VCALENDAR'].join('\r\n')
async function read(page, text, sourceId = '') {
  await (await reveal(page.getByRole('button', { name: 'Importer', exact: true }))).click()
  await page.getByLabel('Velg fil', { exact: true }).setInputFiles({ name: 'invented-continuation.ics', mimeType: 'text/calendar', buffer: Buffer.from(text) })
  if (sourceId) await (await reveal(page.getByLabel('Ny kilde eller oppdatering', { exact: true }))).selectOption(sourceId)
  await (await reveal(page.getByRole('button', { name: 'Vis forhåndsvisning', exact: true }))).click()
  await expect(page.locator('.document-preview')).toBeVisible()
}
async function confirm(page) {
  await (await reveal(page.getByRole('button', { name: 'Importer valgte', exact: true }))).click()
  await expect(page.getByText('Planen er lagret:', { exact: false })).toBeVisible()
}
