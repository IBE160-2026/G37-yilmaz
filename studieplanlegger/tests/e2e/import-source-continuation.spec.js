test('continuation: a genuinely stale preview explains its invalidity and retains choices after refresh', async ({ page }, info) => {
  await page.goto('/')
  await page.evaluate(async () => {
    const { parseDocumentCsv } = await import('/src/document-parsers.js')
    const { createDocumentImportPreview, refreshDocumentImportPreview } = await import('/src/import-preview.js')
    const { renderDocumentImportPreview } = await import('/src/document-import.js')
    const text = 'title;dtstart;dtend\nInvented stale activity;2041-03-01T10:00:00Z;2041-03-01T11:00:00Z'
    const hash = [...new Uint8Array(await crypto.subtle.digest('SHA-256', new TextEncoder().encode(text)))].map(byte => byte.toString(16).padStart(2, '0')).join('')
    let state = { schemaVersion: 1, tasks: [] }
    let preview = createDocumentImportPreview(state, { ...parseDocumentCsv(text), contentHash: hash })
    const container = document.createElement('main'); document.body.replaceChildren(container)
    const show = () => renderDocumentImportPreview(container, preview, { getState: () => state, onRefresh: () => { preview = refreshDocumentImportPreview(state, preview); show() }, onConfirm: async candidate => { window.syntheticSaved = candidate; return { ok: true } } })
    show()
    window.changeSyntheticState = () => { state = { ...state, importSources: [] } }
  })
  await (await reveal(page.getByLabel('Navn', { exact: true }))).fill('My invented reviewed title')
  await page.evaluate(() => window.changeSyntheticState())
  await (await reveal(page.getByLabel('Navn', { exact: true }))).fill('My invented reviewed title retained')
  await expect(page.locator('.document-preview > [role=status]')).not.toContainText('0 legges til')
  await expect(page.locator('.document-preview > [role=status]')).toContainText(/endret|utdatert|gyldig/i)
  await (await reveal(page.getByRole('button', { name: 'Importer valgte', exact: true }))).click()
  expect(await page.evaluate(() => window.syntheticSaved)).toBeUndefined()
  await page.screenshot({ path: info.outputPath('stale-preview.png') })
  await refresh(page)
  await expect(page.getByLabel('Navn', { exact: true })).toHaveValue('My invented reviewed title retained')
  await (await reveal(page.getByRole('button', { name: 'Importer valgte', exact: true }))).click()
  expect(await page.evaluate(() => window.syntheticSaved.planner.events[0].title)).toBe('My invented reviewed title retained')
})

