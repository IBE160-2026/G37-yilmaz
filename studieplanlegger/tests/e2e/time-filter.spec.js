test('completion removes a hit with relevant focus, undo restores eligibility and tied order survives edit and reopen', async ({ page, context }, testInfo) => {
  await seed(page, choices)
  await filter(page)
  const selected = choices[1]
  await openMenu(page, selected.title)
  await checkbox(page, selected.title).focus()
  await page.keyboard.press('Space')
  expect(await ids(page)).toEqual(expectedIds.filter(id => id !== selected.id))
  await expect(page.locator('#filter-summary')).toHaveText('4 forslag innen 30 minutter.')
  await expect(checkbox(page, choices[4].title)).toBeFocused()
  await navigate(page, 'all')
  await expect(checkbox(page, selected.title)).toBeChecked()
  await page.locator('.contextual-undo').getByRole('button', { name: 'Angre siste endring' }).click()
  await navigate(page, 'time')
  expect(await ids(page)).toEqual(expectedIds)
  await showAlternatives(page)
  await openMenu(page, selected.title)
  await edit(page, selected.title).click()
  await page.locator('#course').fill('Rettet emne')
  await save(page).click()
  expect(await ids(page)).toEqual(expectedIds)
  expect((await saved(page)).tasks.map(item => item.id)).toEqual(choices.map(item => item.id))
  expect(await writes(page)).toHaveLength(3)
  await page.close()
  const reopened = await context.newPage()
  await reopened.goto('/')
  await filter(reopened)
  expect(await ids(reopened)).toEqual(expectedIds)
  await expect(row(reopened, selected.title)).toContainText('Rettet emne')
  await expect(checkbox(reopened, selected.title)).not.toBeChecked()
})

test('active filter keeps hits/raw state on failed completion, edit or delete and updates only after retries succeed', async ({ page }, testInfo) => {
  const a = task('a', '2026-08-31T12:00', 20)
  const b = { ...task('b', '2026-09-03T12:00', 30), splittable: false }
  const c = task('c', '2026-10-25T02:30', 30)
  await seed(page, [a, b, c])
  await filter(page)
  let before = await raw(page)
  await page.evaluate(() => { window.failWrite = true })
  await openMenu(page, a.title)
  await checkbox(page, a.title).click()
  await expect(checkbox(page, a.title)).not.toBeChecked()
  await expect(checkbox(page, a.title)).toBeFocused()
  expect(await ids(page)).toEqual([a.id, b.id, c.id])
  expect(await raw(page)).toBe(before)
  await page.evaluate(() => { window.failWrite = false })
  await openMenu(page, a.title)
  await checkbox(page, a.title).click()
  expect(await ids(page)).toEqual([b.id, c.id])
  await expect(checkbox(page, b.title)).toBeFocused()
  before = await raw(page)
  await openMenu(page, b.title)
  await edit(page, b.title).click()
  await page.locator('#remainingMinutes').fill('31')
  await page.evaluate(() => { window.failWrite = true })
  await save(page).click()
  await expect(page.getByRole('status')).toContainText('Endringen ble ikke lagret')
  await expect(page.locator('#remainingMinutes')).toHaveValue('31')
  await expect(row(page, b.title)).toContainText('Hele oppgaven: 30 min')
  expect(await ids(page)).toEqual([b.id, c.id])
  expect(await raw(page)).toBe(before)
  await page.clock.runFor(2000)
  await expect(page.locator('#remainingMinutes')).toHaveValue('31')
  await expect(save(page)).toBeFocused()
  await page.evaluate(() => { window.failWrite = false })
  await save(page).click()
  expect(await ids(page)).toEqual([c.id])
  await expect(page.getByRole('status')).toHaveText('Endringer lagret. Du finner oppgaven under «Alle oppgaver».')
  await expect(page.locator('#available-minutes')).toBeFocused()
  before = await raw(page)
  await deleteTask(page, c.title, false)
  expect(await raw(page)).toBe(before)
  expect(await ids(page)).toEqual([c.id])
  await page.evaluate(() => { window.failWrite = true })
  await deleteTask(page, c.title)
  await expect(row(page, c.title)).toContainText('Oppgaven ble ikke slettet')
  expect(await ids(page)).toEqual([c.id])
  expect(await raw(page)).toBe(before)
  await page.evaluate(() => { window.failWrite = false })
  await deleteTask(page, c.title)
  await expect(rows(page)).toHaveCount(0)
  await expect(page.locator('#empty-tasks')).toContainText('Ingen oppgaver passer tiden')
  await expect(page.locator('#available-minutes')).toBeFocused()
  expect((await saved(page)).tasks).toEqual([{ ...a, completed: true, remainingMinutes: 0 }, { ...b, remainingMinutes: 31 }])
  expect(await writes(page)).toHaveLength(6)
})

test('creating outside the available minutes keeps the empty filter and explains where the saved task is', async ({ page }, testInfo) => {
  await seed(page, [], { view: 'time' })
  await expect(page.locator('#empty-dashboard')).toBeVisible()
  await expect(page.locator('#focus-panel')).toBeHidden()
  const draft = { title: 'Trenger mer tid', course: 'IBE160', deadlineLocal: '2026-09-03T12:00', estimatedMinutes: '31' }
  await page.locator('#empty-onboard-task').click()
  await fillDraft(page, draft)
  await openTaskDetails(page)
  await page.locator('[name=splittable]').uncheck()
  await save(page).click()
  await expect(page.locator('#view-time')).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('#available-minutes')).toHaveValue('30')
  await expect(rows(page)).toHaveCount(0)
  await expect(page.locator('#empty-tasks')).toContainText('Ingen oppgaver passer tiden')
  await expect(page.getByRole('status')).toHaveText('Oppgave lagret. Du finner oppgaven under «Alle oppgaver».')
  expect((await saved(page)).tasks).toHaveLength(1)
  expect(await writes(page)).toHaveLength(1)
  await page.locator('#empty-all').click()
  await expect(row(page, draft.title)).toContainText('Gjenstående arbeid: 31 min')
})

test('task dialog blocks background task, calendar and navigation actions in each view without writes', async ({ page }, testInfo) => {
  const existing = task('too-long', '2026-09-03T15:00', 31)
  await seed(page, [existing])
  const before = await raw(page)
  for (const view of ['time', 'all']) {
    await navigate(page, view)
    await page.locator('#new-task').click()
    await page.locator('#title').fill('Ulagret oppgave')
    await expectModal(page, 'task-form')
    await expect(page.locator('#draft-info')).toBeHidden()
    await page.clock.runFor(2000)
    await expectModal(page, 'task-form')
    await expect(page.locator('#title')).toHaveValue('Ulagret oppgave')
    await expect(page.locator('#view-' + view)).toHaveAttribute('aria-pressed', 'true')
    for (const control of await rows(page).locator('button, input[type=checkbox]').all()) await expect(control).toBeDisabled()
    const calendarEdit = page.locator('#compact-agenda [data-agenda-key="task:too-long"]')
    await expect(calendarEdit).toHaveCount(1)
    await page.locator('#title').focus()
    await calendarEdit.focus()
    await expect(page.locator('#title')).toBeFocused()
    await page.locator('#cancel-task').focus()
    await page.keyboard.press('Tab')
    await expect(page.locator('#title')).toBeFocused()
    await page.keyboard.press('Shift+Tab')
    await expect(page.locator('#cancel-task')).toBeFocused()
    await page.keyboard.press('Escape')
    await expect(page.locator('dialog[open]')).toHaveCount(0)
    await expect(page.locator('#new-task')).toBeFocused()
    expect(await raw(page)).toBe(before)
    expect(await writes(page)).toEqual([])
  }
})
