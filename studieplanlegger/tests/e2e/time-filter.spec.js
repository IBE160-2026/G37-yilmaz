import { expectModal } from './helpers.js'
import { navigate } from './helpers.js'
import { openMenu, openTaskDetails } from './helpers.js'
import { test, expect } from '@playwright/test'
import { task, seed, rows, row, checkbox, edit, save, raw, saved, writes, ids, filter, showAlternatives, deleteTask, fillDraft } from './helpers.js'

const choices = [
  task('future-20', '2026-10-25T02:30', 20),
  task('tie-first-30', '2026-09-03T12:00', 30),
  task('old-20', '2026-08-01T12:00', 20),
  task('late-20', '2026-09-03T23:59', 20),
  task('tie-second-20', '2026-09-03T12:00', 20),
  { ...task('too-long-31', '2026-09-01T12:00', 31), splittable: false },
  task('done-20', '2026-08-01T12:00', 20, true),
]
const expectedIds = ['old-20', 'tie-first-30', 'tie-second-20', 'late-20', 'future-20']

test('30 minutes includes 20/30 across all weeks and overdue tasks, excludes 31/completed, and orders deadlines before durations', async ({ page }, testInfo) => {
  await seed(page, choices)
  const before = await raw(page)
  await filter(page)
  await expect(page.locator('#view-time')).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('#view-week')).toHaveAttribute('aria-pressed', 'false')
  expect(await ids(page)).toEqual(expectedIds)
  await expect(page.locator('#filter-summary')).toHaveText('5 forslag innen 30 minutter.')
  await expect(row(page, choices[2].title).getByText('Forfalt', { exact: true })).toBeVisible()
  await navigate(page, 'all')
  await expect(rows(page)).toHaveCount(choices.length)
  await navigate(page, 'week')
  await navigate(page, 'time')
  await expect(page.locator('#available-minutes')).toHaveValue('30')
  expect(await ids(page)).toEqual(expectedIds)
  // Valid custom input updates the same selection used by quick choices and results.
  await page.locator('#available-minutes').fill('45')
  await navigate(page, 'week')
  await navigate(page, 'time')
  await expect(page.locator('#available-minutes')).toHaveValue('45')
  await expect(page.locator('#filter-summary')).toContainText('45 minutter')
  expect(await ids(page)).toEqual(['old-20', 'too-long-31', 'tie-first-30', 'tie-second-20', 'late-20', 'future-20'])
  await page.locator('#available-minutes').focus()
  await page.locator('#filter-summary').evaluate(element => {
    window.summaryMutations = []
    window.summaryObserver = new MutationObserver(records => window.summaryMutations.push(...records.map(record => record.type)))
    window.summaryObserver.observe(element, { childList: true, characterData: true, subtree: true })
  })
  await page.clock.runFor(2000)
  expect(await page.evaluate(() => window.summaryMutations)).toEqual([])
  await page.evaluate(() => window.summaryObserver.disconnect())
  await expect(page.locator('#available-minutes')).toHaveValue('45')
  await expect(page.locator('#available-minutes')).toBeFocused()
  expect(await raw(page)).toBe(before)
  expect(await saved(page)).toEqual({ schemaVersion: 1, tasks: choices })
  expect(await writes(page)).toEqual([])
  await page.reload()
  await expect(page.locator('#view-overview')).toHaveAttribute('aria-pressed', 'true')
  await navigate(page, 'time')
  await expect(page.locator('#available-minutes')).toHaveValue('30')
  expect(await ids(page)).toEqual(expectedIds)
  expect(await saved(page)).toEqual({ schemaVersion: 1, tasks: choices })
})

test('invalid minutes retain field input and task data, hide stale hits, and recover only on valid resubmission', async ({ page }, testInfo) => {
  await seed(page, choices)
  const before = await raw(page)
  for (const minutes of ['', '0', '-1', '1.5', '2e2', '9007199254740992', 'NaN', ' ']) {
    await filter(page, '30')
    expect(await ids(page)).toEqual(expectedIds)
    await page.locator('#available-minutes').fill(minutes)
    await page.locator('#available-minutes').press('Enter')
    await expect(page.locator('#available-minutes')).toHaveValue(minutes)
    await expect(page.locator('#available-minutes')).toBeFocused()
    await expect(page.locator('#available-minutes')).toHaveAttribute('aria-invalid', 'true')
    await expect(page.locator('#available-minutes')).toHaveAttribute('aria-describedby', 'available-minutes-error')
    await expect(page.locator('#available-minutes-error')).not.toHaveText('')
    await expect(rows(page)).toHaveCount(0)
    await expect(page.locator('#empty-tasks')).not.toBeVisible()
    await page.clock.runFor(1000)
    await expect(rows(page)).toHaveCount(0)
    await expect(page.locator('#available-minutes')).toBeFocused()
    await navigate(page, 'all')
    await expect(rows(page)).toHaveCount(choices.length)
    await navigate(page, 'time')
    await expect(page.locator('#available-minutes')).toHaveValue(minutes)
    await expect(rows(page)).toHaveCount(0)
  }
  await filter(page, '30')
  await expect(page.locator('#available-minutes')).toHaveAttribute('aria-invalid', 'false')
  await expect(page.locator('#available-minutes-error')).toHaveText('')
  expect(await ids(page)).toEqual(expectedIds)
  expect(await raw(page)).toBe(before)
  expect(await writes(page)).toEqual([])
})

