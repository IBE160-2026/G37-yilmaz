test('readable overlapping sessions count union once and can be repaired through calendar on a day without deadlines', async ({ page }, testInfo) => {
  const work = task('overlap', '2026-09-09T12:00', 150)
  await setup(page, [work], [session('first', '10:00', '12:00', '2026-09-08'), session('second', '11:00', '13:00', '2026-09-08')])
  await expect(page.locator('#capacity-summary')).toContainText('30 min ledig')
  await expect(page.locator('#capacity-warnings')).toContainText('bare telt én gang')
  await navigate(page, 'overview')
  await page.locator('#calendar-host').getByRole('button', { name: 'Månedsvisning', exact: true }).click()
  await page.locator('[data-calendar-date="2026-09-08"]').click()
  await expect(page.locator('.calendar-day-list [data-calendar-task]')).toHaveCount(0)
  await expect(page.locator('.calendar-day-list [data-calendar-session]')).toHaveCount(2)
  await expect(page.locator('[data-calendar-date="2026-09-08"]')).toContainText('Ø 2')
  await page.locator('#calendar-host').getByRole('button', { name: 'Agenda', exact: true }).click()
  const calendarEdit = page.locator('#compact-agenda [data-agenda-key="session:second"]')
  await calendarEdit.click()
  await expect(page.locator('#session-startTime')).toHaveValue('11:00')
  await expectModal(page, 'session-form')
  await page.locator('#session-startTime').fill('12:00')
  await sessionSave(page).click()
  await expect(calendarEdit).toBeFocused()
  await expect(page.locator('#compact-agenda .kind-session')).toHaveCount(2)
  await navigate(page, 'capacity')
  await expect(page.locator('#capacity-warnings')).toBeHidden()
  expect((await saved(page)).tasks).toEqual([work])
  expect((await saved(page)).sessions[1].startTime).toBe('12:00')
})

