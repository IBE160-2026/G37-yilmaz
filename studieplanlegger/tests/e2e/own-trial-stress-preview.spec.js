import { test, expect } from '@playwright/test'
import { emptyPlanner } from '../../src/planner.js'
import { stressCalendar, stressCourses, stressCourseCode } from '../fixtures/stress-calendar.js'
import { navigate, reveal, key } from './helpers.js'

const stored = page => page.evaluate(key => JSON.parse(localStorage.getItem(key)), key)
async function openCalendar(page, calendar = stressCalendar()) {
  await navigate(page, 'subjects')
  await (await reveal(page.getByRole('button', { name: 'Finn studieprogram', exact: true }))).click()
  await (await reveal(page.getByRole('button', { name: 'Fra fil eller tekst', exact: true }))).click()
  await page.getByLabel('Velg fil', { exact: true }).setInputFiles({ name: 'synthetic-stress-500.ics', mimeType: 'text/calendar', buffer: Buffer.from(calendar) })
  await (await reveal(page.getByRole('button', { name: 'Vis forhåndsvisning', exact: true }))).click()
  await expect(page.getByRole('heading', { name: 'Dette fant jeg', exact: true })).toBeVisible({ timeout: 35_000 })
}

test('F01 500 events use 25 explicit shared course choices and deferred individual editors, preserving edits and repeat identities', async ({ page }, testInfo) => {
  test.setTimeout(120_000)
  const started = Date.now(), timings = {}, mark = phase => { timings[phase] = Date.now() - started }
  const courses = stressCourses()
  await page.goto('/')
  await page.evaluate(({ key, courses, planner }) => localStorage.setItem(key, JSON.stringify({ schemaVersion: 1, tasks: [], planner: { ...planner, courses } })), { key, courses, planner: emptyPlanner() })
  await page.reload()
  await openCalendar(page)
  mark('firstPreview')
  const preview = page.locator('.document-preview')
  const courseSelect = code => preview.locator(`.document-course-groups select[data-control^='course-choice:["${code}",']`)
  await expect(preview.locator('.document-preview-row')).toHaveCount(525)
  await expect(preview.locator('[data-control^="course-choice:"]')).toHaveCount(25)
  await expect(preview.locator('[data-field=courseChoice]')).toHaveCount(0)
  expect(await preview.locator('select').count()).toBeLessThan(150)
  expect(await preview.locator('option').count()).toBeLessThan(5000)
  const before = await stored(page)
  await preview.getByRole('button', { name: 'Importer valgte', exact: true }).click()
  await expect(preview.locator('[role=alert]')).toContainText('Ingen del av planen er lagret')
  expect(await stored(page)).toEqual(before)
  await expect(preview.locator('[data-field=courseChoice]')).toHaveCount(0)
  await expect(preview.locator('.document-course-groups [aria-invalid=true]')).toHaveCount(25)
  expect(await preview.locator('select').count()).toBeLessThan(150)
  expect(await preview.locator('option').count()).toBeLessThan(5000)
  for (const [index, course] of courses.entries()) {
    // Validation has opened each actual disclosure. Scope this test to its
    // native select instead of repeatedly scanning all 525 accessible rows.
    await expect(courseSelect(course.code)).toBeVisible()
    await courseSelect(course.code).selectOption(course.id)
    const controls = await preview.evaluate(form => ({ individual: form.querySelectorAll('[data-field=courseChoice]').length, unresolved: form.querySelectorAll('.document-course-groups [aria-invalid=true]').length, selects: form.querySelectorAll('select').length }))
    expect(controls.individual).toBe(0)
    expect(controls.unresolved).toBe(24 - index)
    expect(controls.selects).toBeLessThan(150)
  }
  mark('mapped25Courses')
  const row = preview.locator('.document-preview-row').filter({ has: page.locator(':scope > summary', { hasText: '[QA025] Syntetisk aktivitet 499 ·' }) })
  await (await reveal(row.locator(':scope > summary'))).click()
  await row.getByLabel('Sted (valgfritt)', { exact: true }).fill('Syntetisk rom rettet i gjennomgangen')
  // Another group rebuild must retain the open editor and its explicit edit.
  await courseSelect('QA001').selectOption(courses[0].id)
  await expect(row.getByLabel('Sted (valgfritt)', { exact: true })).toHaveValue('Syntetisk rom rettet i gjennomgangen')
  await expect(preview.locator('[data-field=courseChoice]')).toHaveCount(1)
  await preview.getByRole('button', { name: 'Importer valgte', exact: true }).click()
  await expect(page.getByText('Planen er lagret:', { exact: false })).toBeVisible()
  const first = await stored(page)
  mark('saved500')
  expect(first.planner.courses).toEqual(courses)
  expect(first.planner.events).toHaveLength(500)
  for (let index = 0; index < 500; index++) {
    const day = String(1 + Math.floor(index / 25)).padStart(2, '0')
    expect(first.planner.events.find(event => event.title === `[${stressCourseCode(index)}] Syntetisk aktivitet ${index}`)).toMatchObject({ courseId: courses[index % 25].id, start: `2026-11-${day}T09:00:00.000Z`, end: `2026-11-${day}T10:00:00.000Z`, location: index === 499 ? 'Syntetisk rom rettet i gjennomgangen' : `Syntetisk rom ${index % 25 + 1}` })
  }
  await page.reload()
  expect((await stored(page)).planner).toEqual(first.planner)
  mark('reloaded')
  await openCalendar(page)
  await expect(preview.locator('.document-confirmation-summary')).toContainText('500 av 500 aktiviteter klare')
  mark('repeatReady')
  await preview.getByRole('button', { name: 'Importer valgte', exact: true }).click()
  await expect(page.getByText('Planen er lagret:', { exact: false })).toContainText('0 nye, 0 oppdaterte og 500 uendrede')
  expect((await stored(page)).planner).toEqual(first.planner)
  mark('repeatSaved')
  await testInfo.attach('F01 cumulative diagnostic timings (ms)', { body: JSON.stringify(timings), contentType: 'application/json' })
})

test('F01 large preview opens an existing new-course draft synchronously and preserves nested editor focus through full refresh', async ({ page }) => {
  const courses = stressCourses().slice(0, 1)
  await page.goto('/')
  await page.evaluate(({ key, courses, planner }) => localStorage.setItem(key, JSON.stringify({ schemaVersion: 1, tasks: [], planner: { ...planner, courses } })), { key, courses, planner: emptyPlanner() })
  await page.reload()
  await openCalendar(page, stressCalendar({ count: 101 }).replace(/\[QA\d{3}\]/g, '[QA001]'))
  const preview = page.locator('.document-preview')
  const create = preview.getByRole('button', { name: 'Opprett nytt emne for QA001', exact: true, includeHidden: true })
  await (await reveal(create)).click()
  const row = preview.locator('.document-preview-row[data-row-index="102"]')
  const name = row.getByLabel('Emnenavn', { exact: true })
  await expect(name).toBeFocused()
  await name.fill('Syntetisk nytt fellesemne')
  await (await reveal(row.getByLabel('Emnekode (valgfritt)', { exact: true }))).fill('NEW001')
  await row.getByLabel('Kalendersemester', { exact: true }).selectOption('autumn')
  await row.getByLabel('År', { exact: true }).fill('2026')
  await row.locator(':scope > summary').click()
  // This time the complete draft is deferred until the button opens it.
  await (await reveal(create)).click()
  await expect(name).toBeFocused()
  await expect(preview.locator('[role=alert]')).toBeEmpty()
  const year = row.getByLabel('År', { exact: true })
  await (await reveal(year)).focus()
  const refresh = preview.getByRole('button', { name: 'Oppdater forhåndsvisningen', exact: true, includeHidden: true })
  // Preserve the active native editor while invoking the actual complete
  // refresh path, as an external refresh would (DOM click does not move focus).
  await refresh.evaluate(button => button.click())
  await expect(year).toBeFocused()
  await expect(row.locator('.document-course-metadata')).toHaveAttribute('open', '')
  const credits = row.getByLabel('Studiepoeng (valgfritt)', { exact: true })
  await credits.fill(''); await credits.press('e')
  expect(await credits.evaluate(input => input.validity.badInput)).toBe(true)
  await refresh.evaluate(button => button.click())
  await expect(credits).toBeFocused()
  expect(await credits.evaluate(input => input.isConnected && input.validity.badInput)).toBe(true)
  await credits.fill('5')
  await preview.getByRole('button', { name: 'Importer valgte', exact: true }).click()
  await expect(page.getByText('Planen er lagret:', { exact: false })).toBeVisible()
  const state = await stored(page), added = state.planner.courses.find(course => course.code === 'NEW001')
  expect(state.planner.courses).toHaveLength(2)
  expect(state.planner.courses.find(course => course.id === courses[0].id)).toEqual(courses[0])
  expect(added).toMatchObject({ name: 'Syntetisk nytt fellesemne', credits: 5, year: 2026, semester: 'autumn' })
  expect(state.planner.events).toHaveLength(101)
  expect(state.planner.events.every(event => event.courseId === added.id)).toBe(true)
})
