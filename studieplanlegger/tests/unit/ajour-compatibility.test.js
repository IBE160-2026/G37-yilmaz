// The approved 2026-10-26 theme replaces the historical code hash with twelve
// ID-based slots. Domain/backup compatibility assertions above stay unchanged.
const courseSlots = Array.from({ length: 12 }, (_, index) => index + 1)
const rgb = hex => hex.slice(1).match(/../g).map(channel => parseInt(channel, 16) / 255)
const luminance = channels => channels.map(value => value <= 0.04045 ? value / 12.92 : ((value + 0.055) / 1.055) ** 2.4)
  .reduce((sum, value, index) => sum + value * [0.2126, 0.7152, 0.0722][index], 0)
function contrast(first, second) {
  const values = [luminance(first), luminance(second)].sort((a, b) => b - a)
  return (values[0] + 0.05) / (values[1] + 0.05)
}
function semanticColors(theme = 'light') {
  const css = readFileSync(new URL('../../src/redesign.css', import.meta.url), 'utf8')
  const root = css.match(/:root\s*\{([^}]+)\}/)[1]
  const overrides = theme === 'dark' ? css.match(/html\[data-theme=['"]dark['"]\]\s*\{([^}]+)\}/)[1] : ''
  return Object.fromEntries([...`${root}\n${overrides}`.matchAll(/--([\w-]+):\s*(#[\da-f]{6})\b/gi)].map(([, name, value]) => [name, rgb(value)]))
}

describe('Ajour course colors preserve allocation and readable pairings', () => {
  it('uses twelve declared semantic course identities even for matching display codes', () => {
    const courses = courseSlots.map(slot => ({ id: `synthetic-compatibility-${String(slot).padStart(2, '0')}`, code: 'SAME101' }))
    registerCourseColors(courses)
    const colors = courses.map(course => courseColor(course.id))
    expect(new Set(colors).size).toBe(12)
    for (const color of colors) expect(semanticColors()).toHaveProperty(color.match(/^var\(--(.+)\)$/)[1])
    registerCourseColors(courses.toReversed().map(course => ({ ...course, code: 'RENAMED' })))
    expect(courses.map(course => courseColor(course.id))).toEqual(colors)
  })

  it.each(['light', 'dark'])('keeps course markers and actual course text accessible in %s', theme => {
    const colors = semanticColors(theme)
    for (const slot of [...courseSlots, 'neutral']) {
      const marker = colors[`course-${slot}-marker`], background = colors[`course-${slot}-bg`], text = colors[`course-${slot}-text`]
      expect(contrast(text, background), `${theme} course ${slot} text`).toBeGreaterThanOrEqual(4.5)
      for (const surface of [background, colors.canvas, colors.surface, colors.field]) expect(contrast(marker, surface), `${theme} course ${slot} marker`).toBeGreaterThanOrEqual(3)
    }
  })

  it('keeps the actual semantic text, action, error and help pairings above 4.5:1', () => {
    const colors = semanticColors()
    const pairs = [
      ...['canvas', 'surface', 'field', 'lavender', 'pink'].map(background => ['ink', background]),
      ...['canvas', 'surface', 'field', 'pink'].map(background => ['muted', background]),
      ['button-text', 'accent'], ['button-text', 'accent-hover'],
      ['danger', 'danger-wash'], ['warn', 'warn-wash'], ['success', 'green-wash'],
    ]
    for (const [foreground, background] of pairs) {
      expect(contrast(colors[foreground], colors[background]), `${foreground} on ${background}`).toBeGreaterThanOrEqual(4.5)
    }
  })

  it('keeps field borders and focus outlines distinct from their adjacent surfaces', () => {
    const colors = semanticColors()
    for (const surface of ['canvas', 'surface', 'field']) {
      expect(contrast(colors['field-border'], colors[surface]), `field border on ${surface}`).toBeGreaterThanOrEqual(3)
      expect(contrast(colors.focus, colors[surface]), `focus on ${surface}`).toBeGreaterThanOrEqual(3)
    }
  })
})
