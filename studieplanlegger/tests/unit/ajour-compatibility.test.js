function memoryStorage(state = legacyState) {
  const values = new Map([['studieplanlegger:v1', JSON.stringify(state)]])
  const backing = {
    getItem: vi.fn(key => values.get(key) ?? null),
    setItem: vi.fn((key, value) => values.set(key, value)),
    removeItem: vi.fn(key => values.delete(key)),
  }
  return { values, backing, storage: createStorage(() => backing) }
}
